function randchar()
  local c
  repeat
    c = string.char(rnd(33, 126))
  until c ~= "@"
  return c
end

field = {}
robot = { x = 1, y = 1 }
state = GAME
message = ""

function cell(x, y, ch, col)
  print(ch, (x - 1) * SPW, (y - 1) * SPH, col)
end

function place()
  local x, y
  repeat
    x, y = rnd(COLS), rnd(TOP, BOT)
  until not (field[y] and field[y][x])
  return x, y
end

function put(x, y, ch, text, kitten)
  field[y] = field[y] or {}
  field[y][x] = { ch = ch, text = text, kitten = kitten,
    col = COLORS[rnd(#COLORS)] }
end

function pick(n)
  local idx = {}
  for i = 1, #objects do
    idx[i] = i
  end
  for i = #idx, 2, -1 do
    local j = rnd(i)
    idx[i], idx[j] = idx[j], idx[i]
  end
  local ret = {}
  for i = 1, n do
    ret[i] = objects[idx[i]]
  end
  return ret
end

function restart()
  field = {}
  state = GAME
  local items = pick(NKI)
  message = fmt("Найдите котёнка среди %d бессмысленных предметов", #items)
  local x, y = place()
  robot.x, robot.y = x, y
  for i = 1, #items do
    x, y = place()
    put(x, y, randchar(), items[i])
  end
  x, y = place()
  put(x, y, randchar(), nil, true)
end

function move(dx, dy)
  local x, y = robot.x + dx, robot.y + dy
  if x < 1 or x > COLS or y < TOP or y > BOT then
    return
  end
  local o = field[y] and field[y][x]
  if not o then
    robot.x, robot.y = x, y
  elseif o.kitten then
    state = WIN
  else
    message = o.text
  end
end

function wrap(text, maxw)
  local lines, line = {}, ""
  for w in text:gmatch("%S+") do
    local t = line == "" and w or line .. " " .. w
    if font:size(t) <= maxw then
      line = t
    else
      if line ~= "" then
        lines[#lines + 1] = line
      end
      line = w
    end
  end
  if line ~= "" then
    lines[#lines + 1] = line
  end
  return lines
end

function draw()
  clear(0)
  local title = "РОБОТ ИЩЕТ КОТЁНКА"
  local tw = font:size(title)
  print(title, (W - tw) / 2, 0, 10)
  for y = TOP, BOT do
    local row = field[y]
    if row then
      for x, o in pairs(row) do
        cell(x, y, o.ch, o.col)
      end
    end
  end
  cell(robot.x, robot.y, "@", 7)
  local lines = wrap(message, W - 2)
  print(lines[1] or "", 1, (MSG1 - 1) * SPH, 6)
  print(lines[2] or "", 1, (MSG2 - 1) * SPH, 6)
  if state == WIN then
    local bx = floor((W - WINW) / 2)
    local by = floor((H - WINH) / 2)
    WINBOX:blend(screen, bx, by)
    print(WINMSG1, floor((W - (font:size(WINMSG1))) / 2), by + SPH, 10)
    print(WINMSG2, floor((W - (font:size(WINMSG2))) / 2), by + 2 * SPH, 6)
  end
end

function handle(r, v)
  if r ~= "keydown" then
    return
  end
  if state == WIN then
    if v == "space" then
      restart()
    end
  elseif v == "up" or v == "w" then
    move(0, -1)
  elseif v == "down" or v == "s" then
    move(0, 1)
  elseif v == "left" or v == "a" then
    move(-1, 0)
  elseif v == "right" or v == "d" then
    move(1, 0)
  elseif v == "space" then
    restart()
  end
end

restart()

while sys.running() do
  local r, v = sys.input()
  while r do
    handle(r, v)
    r, v = sys.input()
  end
  draw()
  flip(1, true)
end
